/* 切换语言并保存到 localStorage */
function switchLang(lang){
  localStorage.setItem('lang', lang);
  applyTranslation(lang);
}

/* 应用翻译 */
function applyTranslation(lang){
  // 处理文本和 HTML 内容（支持图标/HTML结构）
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if(lang === 'zh'){
      el.innerHTML = key;
    }else if(langData[key] && langData[key][lang]){
      el.innerHTML = langData[key][lang];
    }
  });

  // 处理 placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if(lang === 'zh'){
      el.placeholder = key;
    }else if(langData[key] && langData[key][lang]){
      el.placeholder = langData[key][lang];
    }
  });

  // 顶栏品牌名
  const brand = document.querySelector('.navbar-brand');
  if(brand && langData["恒毅活动报告系统"]){
    brand.textContent = (lang === 'zh') ? "恒毅活动报告系统"
                                        : langData["恒毅活动报告系统"][lang];
  }
}

/* 页面加载时应用当前语言 */
document.addEventListener('DOMContentLoaded', ()=> {
  const lang = localStorage.getItem('lang') || 'zh';
  applyTranslation(lang);
});
